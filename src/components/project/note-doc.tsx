import type { Note, ProjectDiagram } from "@/types/portfolio";

/**
 * Splits note HTML at the heading that follows the named h2 section, so the
 * diagram can sit at the end of that section. Falls back to the whole note
 * when the section is missing (diagram renders after everything).
 */
function splitAfterSection(html: string, heading: string): [string, string] {
  const sectionStart = html.indexOf(`<h2>${heading}</h2>`);
  if (sectionStart === -1) return [html, ""];
  const nextHeading = html.indexOf("<h2", sectionStart + 1);
  if (nextHeading === -1) return [html, ""];
  return [html.slice(0, nextHeading), html.slice(nextHeading)];
}

function DiagramFigure({ note, diagram }: { note: Note; diagram: ProjectDiagram }) {
  return (
    <figure className="mt-5">
      <figcaption className="mb-2 font-terminal text-[10px] uppercase tracking-widest text-muted-foreground">
        architecture diagram
      </figcaption>
      <a
        href={diagram.href}
        target="_blank"
        rel="noopener noreferrer"
        className="flex justify-center overflow-hidden rounded-md border border-border bg-muted/40 transition-opacity hover:opacity-90 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring"
      >
        {/* eslint-disable-next-line @next/next/no-img-element -- static export, images are unoptimized */}
        <img
          src={diagram.src}
          alt={`Architecture diagram of ${note.title}, generated by GitDiagram`}
          width={diagram.width}
          height={diagram.height}
          loading="lazy"
          // Tall diagrams are capped so they don't swallow the page; full size is one click away.
          className="h-auto max-h-[42rem] w-auto max-w-full"
        />
      </a>
      <p className="mt-2 font-terminal text-[10px] text-muted-foreground">
        generated by gitdiagram · click to explore interactively ↗ ·{" "}
        <a
          href={diagram.src}
          target="_blank"
          rel="noopener noreferrer"
          className="underline underline-offset-2 hover:text-foreground"
        >
          full size
        </a>
      </p>
    </figure>
  );
}

export type NoteDocProps = {
  note: Note;
  className?: string;
};

export function NoteDoc({ note, className }: NoteDocProps) {
  const stack = note.stack ?? [];
  const [beforeDiagram, afterDiagram] = note.diagram ? splitAfterSection(note.html, "Architecture") : [note.html, ""];

  return (
    <div className={cn("grid min-w-0 gap-5 lg:grid-cols-[1fr_16rem] lg:gap-6", className)}>
      <Panel padding="none" variant="elevated" className="min-w-0 overflow-hidden">
        <div className="titlebar-chrome px-4 py-3 sm:px-5">
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <p className="font-terminal text-[10px] text-titlebar-foreground">
                {note.type} / {note.slug}
              </p>
              <h1 className="mt-1 break-anywhere text-base font-medium tracking-tight text-foreground sm:text-lg">
                {note.title}
              </h1>
            </div>
            {note.status && <ProjectStatusReadout status={note.status} />}
          </div>
          <div className="mt-2.5 flex flex-wrap gap-1.5">
            {note.domains.map((domain) => (
              <DomainBadge key={domain} domain={domain} />
            ))}
            {note.org && <TerminalBadge variant="muted">{note.org}</TerminalBadge>}
            {note.dates && <TerminalBadge variant="muted">{note.dates}</TerminalBadge>}
          </div>
        </div>

        <div className="min-w-0 px-4 py-5 sm:px-5 sm:py-6">
          <div
            className="prose-note min-w-0"
            // Sanitized at export time (scripts/vault-export/markdown.ts, rehype-sanitize)
            dangerouslySetInnerHTML={{ __html: beforeDiagram }}
          />
          {note.diagram && <DiagramFigure note={note} diagram={note.diagram} />}
          {afterDiagram && (
            <div
              className="prose-note mt-6 min-w-0"
              dangerouslySetInnerHTML={{ __html: afterDiagram }}
            />
          )}
        </div>

        <ProjectLinkBar project={note} variant="footer" className="px-4 pb-4 sm:px-5" />
      </Panel>

      <aside className="flex min-w-0 flex-col gap-4">
        {stack.length > 0 && (
          <Panel padding="sm">
            <StackReadout stack={stack} />
          </Panel>
        )}

        {note.tags.length > 0 && (
          <Panel padding="sm">
            <p className="font-terminal text-[10px] uppercase tracking-widest text-muted-foreground">
              tags
            </p>
            <div className="mt-2 flex flex-wrap gap-1.5">
              {note.tags.map((tag) => (
                <TerminalBadge key={tag} variant="default">
                  {tag}
                </TerminalBadge>
              ))}
            </div>
          </Panel>
        )}

        <Panel padding="sm">
          <p className="font-terminal text-[10px] text-muted-foreground">updated {note.updated}</p>
        </Panel>
      </aside>
    </div>
  );
}
